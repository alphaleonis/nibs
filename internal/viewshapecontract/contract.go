// Package viewshapecontract holds the view-shaping cases that internal/viewshape
// and the web's table shaping must both pass, and renders them as a TypeScript
// module. web/src/lib/viewShapeContract.test.ts runs that module through the
// web's shaping and drop planning, and this package's tests run the same cases
// through viewshape.Shape and viewshape.StaysInGroup.
//
// A rule that no case exercises can drift on either side without a failure. A
// new shaping rule needs a case whose rows it moves, and `task codegen`.
package viewshapecontract

//go:generate go run ./gen

import (
	"encoding/json"
	"fmt"
	"slices"
	"strings"

	"github.com/alphaleonis/nibs/internal/area"
	"github.com/alphaleonis/nibs/internal/nib"
	"github.com/alphaleonis/nibs/internal/viewshape"
)

// OutputPath is the module-root-relative path of the generated file.
const OutputPath = "web/src/lib/generated/viewShapeContract.ts"

// filterFields pairs each viewshape.Filter field with its name in the web's
// `NibFilter`, in the order the module lists them.
var filterFields = []struct {
	name string
	get  func(viewshape.Filter) []string
}{
	{"type", func(f viewshape.Filter) []string { return f.Type }},
	{"excludeType", func(f viewshape.Filter) []string { return f.ExcludeType }},
	{"priority", func(f viewshape.Filter) []string { return f.Priority }},
	{"excludePriority", func(f viewshape.Filter) []string { return f.ExcludePriority }},
	{"status", func(f viewshape.Filter) []string { return f.Status }},
	{"excludeStatus", func(f viewshape.Filter) []string { return f.ExcludeStatus }},
	{"estimate", func(f viewshape.Filter) []string { return f.Estimate }},
	{"excludeEstimate", func(f viewshape.Filter) []string { return f.ExcludeEstimate }},
	{"tags", func(f viewshape.Filter) []string { return f.Tags }},
	{"excludeTags", func(f viewshape.Filter) []string { return f.ExcludeTags }},
}

// Render returns the full generated TypeScript module. It fails on a case the
// module cannot state, such as one sorted other than by viewshape.SortOrder.
func Render() (string, error) {
	var b strings.Builder
	b.WriteString(header)
	b.WriteString("export const VIEW_SHAPE_CONTRACT: readonly ShapeCase[] = [\n")
	for _, c := range Cases() {
		if c.View.Sort != viewshape.SortOrder {
			return "", fmt.Errorf("case %q: sort %q has no web counterpart in this module", c.Name, c.View.Sort)
		}
		b.WriteString("  {\n")
		fmt.Fprintf(&b, "    name: %s,\n", jsString(c.Name))
		fmt.Fprintf(&b, "    note: %s,\n", jsString(c.Note))
		fmt.Fprintf(&b, "    level: %s,\n", jsString(string(c.View.Level)))
		b.WriteString("    nibs: [\n")
		for _, n := range wireNibs(c.Nibs) {
			fmt.Fprintf(&b, "      %s,\n", n)
		}
		b.WriteString("    ],\n")
		b.WriteString("    areas: [\n")
		for _, a := range wireAreas(c.View.Areas) {
			fmt.Fprintf(&b, "      %s,\n", a)
		}
		b.WriteString("    ],\n")
		fmt.Fprintf(&b, "    filter: %s,\n", renderFilter(c.View.Filter))
		fmt.Fprintf(&b, "    collapsed: %s,\n", jsStrings(collapsedRowIDs(c.View)))
		b.WriteString("    rows: [\n")
		for _, r := range c.Want {
			fmt.Fprintf(&b, "      %s,\n", renderRow(r))
		}
		b.WriteString("    ],\n")
		b.WriteString("    reorders: [\n")
		for _, r := range c.Reorders {
			fmt.Fprintf(&b, "      { from: %s, to: %s, stays: %t },\n", jsString(r.From), jsString(r.To), r.Stays)
		}
		b.WriteString("    ],\n")
		b.WriteString("  },\n")
	}
	b.WriteString("];\n")
	return b.String(), nil
}

const header = `// Code generated by internal/viewshapecontract. DO NOT EDIT.
// Regenerate with ` + "`task codegen`" + `.
//
// View-shaping cases that Go's viewshape.Shape and the web's table shaping must
// both pass. viewShapeContract.test.ts runs each case through the web's
// shaping and requires these rows, and asks its drop planning each reorder.
//
// ` + "`nibs`" + ` are listed as the server sends them to the table: in the order of
// ` + "`nibs(sort: { field: ORDER })`" + `, with the effective type and priority and the
// resolved parent. The table applies no column sort.

/** One nib as the table query delivers it. */
export interface ShapeCaseNib {
  readonly id: string;
  readonly title: string;
  readonly status: string;
  readonly type: string;
  readonly priority: string;
  readonly estimate: string;
  readonly tags: readonly string[];
  /** The resolved parent, or null for a root and for a link naming no nib. */
  readonly parentId: string | null;
  readonly milestone: string;
  readonly milestoneOrder: string;
  readonly area: string;
}

/** The metadata fields of a ` + "`NibFilter`" + `, each set only when non-empty. */
export type ShapeCaseFilterKey =
  | "type"
  | "excludeType"
  | "priority"
  | "excludePriority"
  | "status"
  | "excludeStatus"
  | "estimate"
  | "excludeEstimate"
  | "tags"
  | "excludeTags";

/** The ordering group a reorder of a row stays within. */
export interface ShapeCaseGroup {
  /** The ordering key, as ` + "`OrderScope`" + ` names it in lower case. */
  readonly axis: string;
  /** The group within its axis: for "parent", the resolved parent or "" for the root. */
  readonly id: string;
}

/** One declared area as ` + "`Config.areas`" + ` delivers it. */
export interface ShapeCaseArea {
  readonly path: string;
  readonly name: string;
  readonly description: string;
  readonly color: string;
  readonly depth: number;
}

/** One expected row. */
export interface ShapeCaseRow {
  /** The nib the row shows, or null for a section row that no nib heads. */
  readonly id: string | null;
  readonly depth: number;
  /** The section the row heads or belongs to, or null in a view without sections. */
  readonly section: string | null;
  /** Whether the row heads ` + "`section`" + `. */
  readonly header: boolean;
  readonly dimmed: boolean;
  readonly hasChildren: boolean;
  /** Null when no reorder can address the row. */
  readonly group: ShapeCaseGroup | null;
}

export interface ShapeCase {
  readonly name: string;
  /** Which rule the case pins. */
  readonly note: string;
  /** A ` + "`ViewLevel`" + `. */
  readonly level: string;
  readonly nibs: readonly ShapeCaseNib[];
  /** The areas vocabulary the view is bound to. */
  readonly areas: readonly ShapeCaseArea[];
  readonly filter: { readonly [K in ShapeCaseFilterKey]?: readonly string[] };
  /** The ids of the collapsed rows, a section no nib heads by the web's row id for it. */
  readonly collapsed: readonly string[];
  readonly rows: readonly ShapeCaseRow[];
  readonly reorders: readonly ShapeCaseReorder[];
}

/**
 * Whether moving the row of nib ` + "`from`" + ` to the position of the row of nib ` + "`to`" + `
 * keeps it in its ordering group, as viewshape.StaysInGroup answers.
 */
export interface ShapeCaseReorder {
  readonly from: string;
  readonly to: string;
  readonly stays: boolean;
}

`

// wireNibs renders nibs as the table query delivers them: sorted as the order
// sort sorts them, with the fields the GraphQL resolvers report.
func wireNibs(nibs []*nib.Nib) []string {
	ordered := slices.Clone(nibs)
	nib.SortByOrder(ordered)
	present := make(map[string]bool, len(ordered))
	for _, n := range ordered {
		present[n.ID] = true
	}
	out := make([]string, 0, len(ordered))
	for _, n := range ordered {
		parent := "null"
		if present[n.Parent] {
			parent = jsString(n.Parent)
		}
		out = append(out, fmt.Sprintf(
			"{ id: %s, title: %s, status: %s, type: %s, priority: %s, estimate: %s, tags: %s, parentId: %s, milestone: %s, milestoneOrder: %s, area: %s }",
			jsString(n.ID), jsString(n.Title), jsString(n.Status), jsString(n.EffectiveType()),
			jsString(n.EffectivePriority()), jsString(n.Estimate), jsStrings(n.Tags), parent,
			jsString(n.Milestone), jsString(n.MilestoneOrder), jsString(n.Area),
		))
	}
	return out
}

// wireAreas renders a vocabulary as `Config.areas` delivers it: in Paths order,
// each node with its depth from a root.
func wireAreas(areas *area.Vocabulary) []string {
	paths := areas.Paths()
	out := make([]string, 0, len(paths))
	for _, path := range paths {
		_, name := area.SplitPath(path)
		node := areas.Get(path)
		out = append(out, fmt.Sprintf("{ path: %s, name: %s, description: %s, color: %s, depth: %d }",
			jsString(path), jsString(name), jsString(node.Description), jsString(node.Color),
			strings.Count(path, area.PathSeparator)))
	}
	return out
}

// collapsedRowIDs returns the web's row ids for the rows v collapses, sorted. A
// section no nib heads takes the id `sectionRowId` in web/src/lib/tree.ts gives
// it: a leftover's key as it is, any other key escaped.
func collapsedRowIDs(v viewshape.View) []string {
	ids := sortedKeys(v.Collapsed)
	for _, key := range sortedKeys(v.CollapsedSections) {
		if viewshape.IsLeftoverSection(key) {
			ids = append(ids, key)
		} else {
			ids = append(ids, "/section:"+key+"_")
		}
	}
	slices.Sort(ids)
	return ids
}

func renderFilter(f viewshape.Filter) string {
	var parts []string
	for _, field := range filterFields {
		if values := field.get(f); len(values) > 0 {
			parts = append(parts, fmt.Sprintf("%s: %s", field.name, jsStrings(values)))
		}
	}
	if len(parts) == 0 {
		return "{}"
	}
	return "{ " + strings.Join(parts, ", ") + " }"
}

func renderRow(r viewshape.Row) string {
	id := "null"
	if r.NibID != "" {
		id = jsString(r.NibID)
	}
	section := "null"
	if r.Section != "" {
		section = jsString(r.Section)
	}
	group := "null"
	if r.Group != (viewshape.Group{}) {
		group = fmt.Sprintf("{ axis: %s, id: %s }", jsString(string(r.Group.Axis)), jsString(r.Group.ID))
	}
	return fmt.Sprintf("{ id: %s, depth: %d, section: %s, header: %t, dimmed: %t, hasChildren: %t, group: %s }",
		id, r.Depth, section, r.Header, r.Dimmed, r.HasChildren, group)
}

func sortedKeys(set map[string]bool) []string {
	keys := make([]string, 0, len(set))
	for k, v := range set {
		if v {
			keys = append(keys, k)
		}
	}
	slices.Sort(keys)
	return keys
}

// jsString renders s as a string literal. A JSON string is a valid JavaScript
// string literal.
func jsString(s string) string {
	out, err := json.Marshal(s)
	if err != nil {
		panic(err) // json.Marshal fails on no string
	}
	return string(out)
}

func jsStrings(values []string) string {
	quoted := make([]string, 0, len(values))
	for _, v := range values {
		quoted = append(quoted, jsString(v))
	}
	return "[" + strings.Join(quoted, ", ") + "]"
}
