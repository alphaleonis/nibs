package filterlangcontract

import (
	"fmt"
	"strings"
	"unicode/utf16"
)

// InputOutputPath is the module-root-relative path of the generated
// highlighting and completion cases.
const InputOutputPath = "web/src/lib/generated/filterInputContract.ts"

// The generated cases count offsets in UTF-16 code units, the unit of a
// JavaScript string index, so they hold what the web's functions return. The
// Go suite converts filterlang's byte offsets before it compares.

// WireSpan is a span as the web's tokenizeSpans returns it.
type WireSpan struct {
	Start int    `json:"start"`
	End   int    `json:"end"`
	Kind  string `json:"kind"`
}

// WireRel is a relationship-id value as the web's relTokenValueContext returns
// it.
type WireRel struct {
	Field       string   `json:"field"`
	Name        string   `json:"name"`
	Fragment    string   `json:"fragment"`
	Start       int      `json:"start"`
	End         int      `json:"end"`
	SearchTypes []string `json:"searchTypes,omitempty"`
}

// WireCompletion is the web's getCompletion result, with what its apply
// returns for each item.
type WireCompletion struct {
	Kind    string      `json:"kind"`
	Items   []string    `json:"items"`
	Applied []WireApply `json:"applied"`
}

// WireApply is the text and caret that accepting one item leaves.
type WireApply struct {
	Text  string `json:"text"`
	Caret int    `json:"caret"`
}

// WantSpans returns the case's spans with UTF-16 offsets.
func (c SpanCase) WantSpans() []WireSpan {
	out := []WireSpan{}
	at := 0
	for _, p := range c.Spans {
		end := at + utf16Len(p.Text)
		out = append(out, WireSpan{Start: at, End: end, Kind: string(p.Kind)})
		at = end
	}
	return out
}

// Input returns the case's text without Caret, and the cursor's offset in
// UTF-16 code units.
func (c CompletionCase) Input() (string, int) {
	return splitCaret(c.Text)
}

// WantRel returns the expected relationship-id value, or nil when the cursor
// sits in none.
func (c CompletionCase) WantRel() *WireRel {
	if c.Rel == nil {
		return nil
	}
	before, rest, _ := strings.Cut(c.Rel.Range, "[")
	fragment, _, _ := strings.Cut(rest, "]")
	start := utf16Len(before)
	return &WireRel{
		Field: c.Rel.Field, Name: c.Rel.Name, Fragment: fragment,
		Start: start, End: start + utf16Len(fragment), SearchTypes: c.Rel.SearchTypes,
	}
}

// WantCompletion returns the expected completion, or nil when there is none.
func (c CompletionCase) WantCompletion() *WireCompletion {
	if len(c.Offers) == 0 {
		return nil
	}
	w := &WireCompletion{Kind: string(c.Kind)}
	for _, o := range c.Offers {
		text, caret := splitCaret(o.Result)
		w.Items = append(w.Items, o.Item)
		w.Applied = append(w.Applied, WireApply{Text: text, Caret: caret})
	}
	return w
}

// splitCaret removes the first Caret from s and returns its offset in UTF-16
// code units.
func splitCaret(s string) (string, int) {
	before, after, _ := strings.Cut(s, Caret)
	return before + after, utf16Len(before)
}

// UTF16Offset returns the offset in UTF-16 code units of byte offset i of s.
func UTF16Offset(s string, i int) int {
	return utf16Len(s[:i])
}

func utf16Len(s string) int {
	n := 0
	for _, r := range s {
		n += utf16.RuneLen(r)
	}
	return n
}

// RenderInput returns the full generated TypeScript module of highlighting and
// completion cases.
func RenderInput() string {
	var b strings.Builder
	b.WriteString(inputHeader)
	b.WriteString("export const FILTER_SPAN_CONTRACT: readonly FilterSpanCase[] = [\n")
	for _, c := range SpanCases() {
		b.WriteString("  {\n")
		fmt.Fprintf(&b, "    name: %s,\n", jsLiteral(c.Name))
		fmt.Fprintf(&b, "    text: %s,\n", jsLiteral(c.Text()))
		writeAreas(&b, c.Areas)
		fmt.Fprintf(&b, "    spans: %s,\n", jsLiteral(c.WantSpans()))
		b.WriteString("  },\n")
	}
	b.WriteString("];\n\n")
	b.WriteString("export const FILTER_COMPLETION_CONTRACT: readonly FilterCompletionCase[] = [\n")
	for _, c := range CompletionCases() {
		text, cursor := c.Input()
		b.WriteString("  {\n")
		fmt.Fprintf(&b, "    name: %s,\n", jsLiteral(c.Name))
		fmt.Fprintf(&b, "    text: %s,\n", jsLiteral(text))
		fmt.Fprintf(&b, "    cursor: %d,\n", cursor)
		fmt.Fprintf(&b, "    explicit: %t,\n", c.Explicit)
		fmt.Fprintf(&b, "    tags: %s,\n", jsLiteral(nonNil(c.Tags)))
		writeAreas(&b, c.Areas)
		fmt.Fprintf(&b, "    rel: %s,\n", jsLiteral(c.WantRel()))
		fmt.Fprintf(&b, "    completion: %s,\n", jsLiteral(c.WantCompletion()))
		b.WriteString("  },\n")
	}
	b.WriteString("];\n")
	return b.String()
}

const inputHeader = `// Code generated by internal/filterlangcontract. DO NOT EDIT.
// Regenerate with ` + "`task codegen`" + `.
//
// Highlighting and completion cases that Go's filterlang and the web's query
// functions must both pass, run by filterInputContract.test.ts. Offsets count
// UTF-16 code units.

import type { FilterParseCaseArea } from "./filterParseContract";

export interface FilterSpanCase {
  readonly name: string;
  readonly text: string;
  /** The declared area vocabulary, or null to highlight with none. */
  readonly areas: readonly FilterParseCaseArea[] | null;
  /** What ` + "`tokenizeSpans`" + ` returns. */
  readonly spans: readonly { readonly start: number; readonly end: number; readonly kind: string }[];
}

export interface FilterCompletionCase {
  readonly name: string;
  readonly text: string;
  readonly cursor: number;
  /** Whether the user asked for the completion, as by Ctrl+Space. */
  readonly explicit: boolean;
  readonly tags: readonly string[];
  /** The declared area vocabulary, or null for none. */
  readonly areas: readonly FilterParseCaseArea[] | null;
  /** What ` + "`relTokenValueContext`" + ` returns. */
  readonly rel: {
    readonly field: string;
    readonly name: string;
    readonly fragment: string;
    readonly start: number;
    readonly end: number;
    readonly searchTypes?: readonly string[];
  } | null;
  /** What ` + "`getCompletion`" + ` returns, with what its ` + "`apply`" + ` returns for each item. */
  readonly completion: {
    readonly kind: string;
    readonly items: readonly string[];
    readonly applied: readonly { readonly text: string; readonly caret: number }[];
  } | null;
}

`
