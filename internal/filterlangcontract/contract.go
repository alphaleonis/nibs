// Package filterlangcontract holds the filter-parsing cases that
// internal/filterlang and the web's query parser must both pass, and renders
// them as a TypeScript module. web/src/lib/query/filterParseContract.test.ts
// runs that module through the web's parseQuery and serializeQuery, and this
// package's tests run the same cases through filterlang.ParseWithAreas and
// filterlang.Serialize.
//
// A rule that no case exercises can drift on either side without a failure. A
// new parsing rule needs a case whose result it changes, and `task codegen`.
package filterlangcontract

//go:generate go run ./gen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"strings"
	"unicode/utf16"

	"github.com/alphaleonis/nibs/internal/area"
)

// OutputPath is the module-root-relative path of the generated file.
const OutputPath = "web/src/lib/generated/filterParseContract.ts"

// Render returns the full generated TypeScript module.
func Render() string {
	var b strings.Builder
	b.WriteString(header)
	b.WriteString("export const FILTER_PARSE_CONTRACT: readonly FilterParseCase[] = [\n")
	for _, c := range Cases() {
		b.WriteString("  {\n")
		fmt.Fprintf(&b, "    name: %s,\n", jsLiteral(c.Name))
		fmt.Fprintf(&b, "    text: %s,\n", jsLiteral(c.Text))
		if c.Areas == nil {
			b.WriteString("    areas: null,\n")
		} else {
			b.WriteString("    areas: [\n")
			for _, a := range wireAreas(c.Areas) {
				fmt.Fprintf(&b, "      %s,\n", a)
			}
			b.WriteString("    ],\n")
		}
		fmt.Fprintf(&b, "    filter: %s,\n", jsLiteral(c.Want))
		fmt.Fprintf(&b, "    invalidTokens: %s,\n", jsLiteral(nonNil(c.Invalid)))
		fmt.Fprintf(&b, "    canonical: %s,\n", jsLiteral(c.Canonical))
		b.WriteString("  },\n")
	}
	b.WriteString("];\n")
	return b.String()
}

const header = `// Code generated by internal/filterlangcontract. DO NOT EDIT.
// Regenerate with ` + "`task codegen`" + `.
//
// Filter-parsing cases that Go's filterlang.ParseWithAreas and the web's
// parseQuery must both pass. filterParseContract.test.ts parses each text and
// requires the filter and invalid tokens, then serializes the result and
// requires the canonical text.

/** One declared area as ` + "`Config.areas`" + ` delivers it. */
export interface FilterParseCaseArea {
  readonly path: string;
  readonly name: string;
  readonly description: string;
  readonly color: string;
  readonly depth: number;
}

export interface FilterParseCase {
  readonly name: string;
  readonly text: string;
  /** The declared area vocabulary, or null to parse with none. */
  readonly areas: readonly FilterParseCaseArea[] | null;
  /** The ` + "`NibFilter`" + ` keys the text sets. */
  readonly filter: { readonly [key: string]: string | boolean | readonly string[] };
  readonly invalidTokens: readonly string[];
  /** The text the parse result serializes to. */
  readonly canonical: string;
}

`

// wireAreas renders a vocabulary as `Config.areas` delivers it: in Paths order,
// each node with its depth from a root.
func wireAreas(areas *area.Vocabulary) []string {
	paths := areas.Paths()
	out := make([]string, 0, len(paths))
	for _, path := range paths {
		_, name := area.SplitPath(path)
		node := areas.Get(path)
		out = append(out, fmt.Sprintf("{ path: %s, name: %s, description: %s, color: %s, depth: %d }",
			jsLiteral(path), jsLiteral(name), jsLiteral(node.Description), jsLiteral(node.Color),
			strings.Count(path, area.PathSeparator)))
	}
	return out
}

func nonNil(values []string) []string {
	if values == nil {
		return []string{}
	}
	return values
}

// jsLiteral renders v as JSON, which is a valid JavaScript literal, with every
// character outside ASCII escaped so the generated file shows each one. A
// NibFilter renders with its GraphQL field names and without its nil fields,
// as the web's parser omits the keys it does not set.
func jsLiteral(v any) string {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(v); err != nil {
		panic(err) // The cases hold only strings, string lists and Booleans.
	}
	var b strings.Builder
	for _, r := range strings.TrimSuffix(buf.String(), "\n") {
		switch {
		case r < 0x80:
			b.WriteRune(r)
		case r > 0xFFFF:
			hi, lo := utf16.EncodeRune(r)
			fmt.Fprintf(&b, `\u%04x\u%04x`, hi, lo)
		default:
			fmt.Fprintf(&b, `\u%04x`, r)
		}
	}
	return b.String()
}
